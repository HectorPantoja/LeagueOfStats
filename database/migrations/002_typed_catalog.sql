CREATE TABLE IF NOT EXISTS GameCatalogs (
 Region TEXT NOT NULL, Locale TEXT NOT NULL, Version TEXT NOT NULL,
 UpdatedUtc TEXT NOT NULL, PRIMARY KEY(Region, Locale));
CREATE TABLE IF NOT EXISTS Champions (
 Region TEXT NOT NULL, Locale TEXT NOT NULL, Id TEXT NOT NULL, NumericKey INTEGER NOT NULL,
 Name TEXT NOT NULL, Payload TEXT NOT NULL,
 PRIMARY KEY(Region, Locale, Id),
 FOREIGN KEY(Region, Locale) REFERENCES GameCatalogs(Region, Locale) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS Items (
 Region TEXT NOT NULL, Locale TEXT NOT NULL, Id INTEGER NOT NULL, Name TEXT NOT NULL,
 Payload TEXT NOT NULL, PRIMARY KEY(Region, Locale, Id),
 FOREIGN KEY(Region, Locale) REFERENCES GameCatalogs(Region, Locale) ON DELETE CASCADE);
